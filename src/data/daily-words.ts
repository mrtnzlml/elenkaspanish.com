export const dailyWords: DailyWord[] = wordsByMonth.flat();

/**
 * Word for the visitor's LOCAL calendar date, so holiday words land on the
 * holiday wherever the visitor is (same rule as seasonFor).
 */
export function wordOfTheDay(date: Date): DailyWord {
  const month = wordsByMonth[date.getMonth()];
  return month[Math.min(date.getDate(), month.length) - 1];
}

/** A random word other than `current`. */
export function randomWord(current?: DailyWord, rand: () => number = Math.random): DailyWord {
  const pool = current ? dailyWords.filter((w) => w.es !== current.es) : dailyWords;
  return pool[Math.floor(rand() * pool.length)];
}
